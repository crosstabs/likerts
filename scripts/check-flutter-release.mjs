import {spawn} from 'node:child_process';
import {readFile,writeFile,mkdir,cp} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join,dirname,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url));
const [out,work,version]=process.argv.slice(2);assert.ok(out&&work&&version);
const flutter=process.env.FLUTTER_COMMAND??join(root,'.tools/flutter/bin/flutter');
const run=(command,args,cwd=root)=>new Promise((resolve,reject)=>{console.error(`Flutter install gate: ${command} ${args.join(' ')}`);const child=spawn(command,args,{cwd,stdio:['ignore','pipe','pipe']});child.stdout.on('data',c=>process.stderr.write(c));child.stderr.on('data',c=>process.stderr.write(c));child.on('error',reject);child.on('close',code=>code===0?resolve():reject(new Error(`${command} exited ${code}`)));});
const source=join(root,'sdks/flutter'),stage=join(work,'flutter-artifact','likerts');await mkdir(stage,{recursive:true});
const pubspec=await readFile(join(source,'pubspec.yaml'),'utf8');assert.ok(pubspec.includes(`version: ${version}`));
const publishTo=pubspec.match(/^publish_to:\s*(.*)$/m)?.[1];assert.ok(publishTo===undefined||publishTo==='none','Use the default pub.dev registry or disable publication');
for(const file of ['pubspec.yaml','lib','README.md','CHANGELOG.md','LICENSE','installation-example'])await cp(join(source,file),join(stage,file),{recursive:true});
const archive=join(out,`likerts-flutter-${version}.tar.gz`);await run('tar',['-czf',archive,'-C',dirname(stage),'likerts']);
const clean=join(work,'flutter-clean');await mkdir(clean);await run('tar',['-xzf',archive,'-C',clean]);
const consumer=join(clean,'consumer');await mkdir(join(consumer,'lib'),{recursive:true});await mkdir(join(consumer,'test'));
await writeFile(join(consumer,'pubspec.yaml'),`name: likerts_install_probe\npublish_to: none\nversion: 1.0.0\nenvironment:\n  sdk: '>=3.8.0 <4.0.0'\ndependencies:\n  flutter:\n    sdk: flutter\n  likerts:\n    path: ../likerts\ndev_dependencies:\n  flutter_test:\n    sdk: flutter\n`);
await cp(join(clean,'likerts/installation-example/checkout_feedback.dart'),join(consumer,'lib/checkout_feedback.dart'));
await writeFile(join(consumer,'test/install_test.dart'),`import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:likerts/advanced_questions.dart';
import 'package:likerts/likerts.dart';
import 'package:likerts/offline_queue.dart';
import 'package:likerts_install_probe/checkout_feedback.dart';
void main() { testWidgets('installed SDK waits for host trigger and dismisses', (tester) async {
  expect(likertsSdkCapability['sdkVersion'], '${version}');
  expect(allocationRemaining(100, {'product': 40}), 60);
  expect(OfflineLimits().maxRecords, 1000);
  final collection = Collection.fromJson({'id':'example','surveyId':'survey','version':1,'placement':'receipt','schema':{'schemaVersion':1,'title':'Package feedback','questions':[{'id':'comment','type':'text','label':'Comment','required':false}]}});
  var dismissed=false;
  await tester.pumpWidget(MaterialApp(home:Scaffold(body:CheckoutFeedback(collection:collection,eligible:true,submitting:false,onSubmit:(_){},onDismiss:(){dismissed=true;}))));
  expect(find.text('Package feedback'), findsNothing);
  await tester.tap(find.text('Give feedback')); await tester.pump();
  expect(find.text('Package feedback'), findsOneWidget);
  await tester.tap(find.text('Dismiss')); await tester.pump();
  expect(dismissed,true); expect(find.text('Package feedback'),findsNothing);
}); }
`);
await run(flutter,['pub','get'],consumer);await run(flutter,['analyze'],consumer);await run(flutter,['test'],consumer);
const bytes=await readFile(archive);
console.log(JSON.stringify({artifacts:[{file:relative(out,archive),kind:'flutter-source-package',bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')}],check:{target:'flutter',passed:true,verification:'Fresh source-archive extraction, independent Flutter pub resolution/analyze and widget trigger/dismissal test'}}));
